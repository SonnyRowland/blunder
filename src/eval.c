int32_t eval_material(Board* board) {
  int32_t total_value = 0;

  for (int rank = 0; rank < 8; rank++) {
    for (int file = 0; file < 8; file++) {
      Piece piece = board->grid[rank][file];

      if (piece == EMPTY) continue;
      if (abs(piece) == W_KING) continue;

      int piece_colour = piece > 0 ? 1 : -1;

      if (piece_colour == 1) {
        total_value += (BASE_VAL[abs(piece)] + PST[piece][rank][file]);
      } else {
        total_value +=
            (BASE_VAL[abs(piece)] + PST[abs(piece)][7 - rank][7 - file]) *
            piece_colour;
      }
    }
  }

  return total_value;
}
